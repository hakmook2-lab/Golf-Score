var I18N=(function(){
  var KEY='golfscore.lang', lang=null, asked=false, LANGS=['ko','ja','en'];
  var NAMES={ko:'한국어',ja:'日本語',en:'English'}, SHORT={ko:'KO',ja:'JA',en:'EN'};
  try{ lang=localStorage.getItem(KEY); }catch(e){}
  if(LANGS.indexOf(lang)<0){
    var nl=((navigator.languages&&navigator.languages[0])||navigator.language||'').toLowerCase();
    if(nl.indexOf('ja')===0){ lang='ja'; }
    else if(nl.indexOf('ko')===0){ lang='ko'; }
    else if(nl.indexOf('en')===0){ lang='en'; }
    else { lang='en'; asked=true; }
  }
  var DICT=lang==='ja'?JA:(lang==='en'?EN:null);
  function set(l){
    try{ localStorage.setItem(KEY,l); }catch(e){}
    location.reload();
  }
  function tr(s){ return (DICT&&Object.prototype.hasOwnProperty.call(DICT,s))?DICT[s]:s; }
  /* index.html 고정 문구 번역 */
  function applyStatic(){
    var d=document.documentElement;
    d.setAttribute('lang',lang);
    document.title=tr('골프 스코어');
    var m=document.querySelector('meta[name="apple-mobile-web-app-title"]'); if(m){ m.setAttribute('content',tr('골프스코어')); }
    var lb=document.getElementById('langBtn'); if(lb){ lb.textContent='🌐 '+SHORT[lang]; }
    if(!DICT){ return; }
    var skip={MAIN:1,SCRIPT:1,STYLE:1};
    (function walkNode(n){
      if(n.nodeType===3){
        var t=n.nodeValue, k=t.trim();
        if(k&&DICT[k]!=null){ n.nodeValue=t.replace(k,DICT[k]); }
        return;
      }
      if(n.nodeType!==1||skip[n.tagName]||n.id==='modalRoot'||n.id==='langBtn'){ return; }
      ['aria-label','placeholder','title'].forEach(function(a){ var v=n.getAttribute(a); if(v&&DICT[v]!=null){ n.setAttribute(a,DICT[v]); } });
      for(var c=n.firstChild;c;c=c.nextSibling){ walkNode(c); }
    })(document.body);
  }
  /* 언어 선택 창: 처음(폰 언어가 한·일·영이 아닐 때) 또는 🌐 버튼을 눌렀을 때 */
  function pick(first){
    if(document.getElementById('langPick')){ return; }
    var ov=document.createElement('div');
    ov.className='ov'; ov.id='langPick'; ov.style.alignItems='center';
    ov.innerHTML='<div class="sheet" style="border-radius:20px;max-width:360px;margin:16px;text-align:center">'+
      '<h3>언어 · 言語 · Language</h3><div style="display:grid;gap:10px;margin-top:14px">'+
      LANGS.map(function(l){ return '<button class="btn'+(l===lang?'':' ghost')+'" data-lang="'+l+'">'+NAMES[l]+(l===lang?' ✓':'')+'</button>'; }).join('')+'</div></div>';
    ov.addEventListener('click',function(e){
      var b=e.target.closest&&e.target.closest('[data-lang]');
      if(!b){ if(!first&&e.target===ov){ ov.parentNode.removeChild(ov); } return; }
      var l=b.getAttribute('data-lang');
      if(l===lang){ try{ localStorage.setItem(KEY,l); }catch(err){} ov.parentNode.removeChild(ov); } else { set(l); }
    });
    document.body.appendChild(ov);
  }
  function askOnce(){ if(asked){ pick(true); } }
  if(document.readyState==='loading'){ document.addEventListener('DOMContentLoaded',function(){ applyStatic(); askOnce(); }); }
  else { applyStatic(); askOnce(); }
  return {lang:lang, set:set, tr:tr, pick:function(){ pick(false); }, names:NAMES};
})();
function TR(s){ return I18N.tr(s); }
